inline bool VerifyFunction(const Function& function, const std::uint8_t* code,
    const std::size_t size, const std::uint32_t loaded_base) noexcept {
    if (code == nullptr || loaded_base == 0U || size != function.size
        || size > kMaximumFunctionSize
        || function.relocation_count > function.relocations.size()) { return false; }
    std::array<std::uint8_t, kMaximumFunctionSize> normalized{};
    SIZE_T copied = 0U;
    if (!ReadProcessMemory(GetCurrentProcess(), code, normalized.data(), size, &copied)
        || copied != size) { return false; }
    const std::uint32_t delta = loaded_base - kScenePreferredBase;
    for (std::size_t index = 0U; index < function.relocation_count; ++index) {
        const std::size_t offset = function.relocations[index];
        if (size < 4U || offset > size - 4U) { return false; }
        std::uint32_t value = 0U;
        std::memcpy(&value, normalized.data() + offset, sizeof(value));
        value -= delta;
        std::memcpy(normalized.data() + offset, &value, sizeof(value));
    }
    std::array<std::uint8_t, 32U> digest{};
    BCRYPT_ALG_HANDLE algorithm = nullptr;
    BCRYPT_HASH_HANDLE hash = nullptr;
    bool valid = false;
    if (BCryptOpenAlgorithmProvider(&algorithm, BCRYPT_SHA256_ALGORITHM, nullptr, 0U) >= 0
        && BCryptCreateHash(algorithm, &hash, nullptr, 0U, nullptr, 0U, 0U) >= 0
        && BCryptHashData(hash, normalized.data(), static_cast<ULONG>(size), 0U) >= 0
        && BCryptFinishHash(hash, digest.data(), static_cast<ULONG>(digest.size()), 0U) >= 0) {
        valid = digest == function.sha256;
    }
    if (hash != nullptr) { BCryptDestroyHash(hash); }
    if (algorithm != nullptr) { BCryptCloseAlgorithmProvider(algorithm, 0U); }
    return valid;
}

inline bool VerifyImage(const std::uint8_t* image, const std::size_t image_size,
    const char* verified_sha256) noexcept {
    if (image == nullptr || !IsReviewedSceneExecutable(verified_sha256)) { return false; }
    const auto base = reinterpret_cast<std::uintptr_t>(image);
    if (base > UINT32_MAX || image_size > UINT32_MAX - base) { return false; }
    for (const auto& function : kFunctions) {
        if (function.rva > image_size || function.size > image_size - function.rva
            || !VerifyFunction(function, image + function.rva, function.size,
                static_cast<std::uint32_t>(base))) { return false; }
    }
    return true;
}

